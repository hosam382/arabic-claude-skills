// يقرأ كل مجلد فيه SKILL.md ويكتب skills-data.js اللي تعرضه الصفحة. شغّله بعد أي تعديل: node build.js
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

export const ROOT = dirname(fileURLToPath(import.meta.url));

// يفصل رأس الملف (frontmatter) عن باقي التعليمات. يرجع null إذا الرأس ناقص
export function parseSkill(text) {
  const src = text.replace(/\r\n/g, '\n');
  const m = src.match(/^---\n([\s\S]*?)\n---\n/);
  if (!m) return null;
  const meta = {};
  for (const line of m[1].split('\n')) {
    const i = line.indexOf(':');
    if (i < 1) return null;
    let value = line.slice(i + 1).trim();
    if (/^(["']).*\1$/.test(value)) value = value.slice(1, -1);
    meta[line.slice(0, i).trim()] = value;
  }
  return { meta, body: src.slice(m[0].length).replace(/^\n+/, '') };
}

export function skillDirs(root = ROOT) {
  return readdirSync(root, { withFileTypes: true })
    .filter((d) => d.isDirectory() && !d.name.startsWith('.') && d.name !== 'node_modules')
    .map((d) => d.name)
    .filter((name) => existsSync(join(root, name, 'SKILL.md')))
    .sort();
}

export function readSkills(root = ROOT) {
  return skillDirs(root).map((dir) => {
    const parsed = parseSkill(readFileSync(join(root, dir, 'SKILL.md'), 'utf8'));
    if (!parsed) throw new Error(`${dir}/SKILL.md: frontmatter is missing or malformed`);
    return { name: parsed.meta.name, description: parsed.meta.description, body: parsed.body };
  });
}

export function renderData(skills) {
  return '// Generated by build.js from */SKILL.md. Do not edit by hand: run `node build.js`.\n'
    + `export const SKILLS = ${JSON.stringify(skills, null, 2)};\n`;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const skills = readSkills();
  writeFileSync(join(ROOT, 'skills-data.js'), renderData(skills));
  console.log(`skills-data.js: ${skills.length} skills (${skills.map((s) => s.name).join(', ')})`);
}
